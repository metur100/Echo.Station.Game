/**
 * Module status and priority-based power allocation.
 *
 * 1. Every module gets a base status (constructing, disabled, quarantined, broken, overheated,
 *    too cold, overgrown). Those reasons win over power problems.
 * 2. Power travels through walls between modules. Broken modules don't conduct, so a broken
 *    corridor can cut a wing off from the reactor ("disconnected").
 * 3. Supply = output of working reactors + what the battery can discharge this tick.
 *    Consumers are served by priority (1 = life support first), then by id. A consumer either gets
 *    its full demand or nothing ("no power").
 * 4. Surplus charges the battery (the `power` resource); deficits drain it.
 */
import { MODULES, levelMultiplier } from '../content/modules';
import { RESEARCH_EFFECTS } from '../content/research';
import { components, type Topology } from '../engine/grid';
import { captainBonus, clamp, conditionEfficiency, hasResearch, tidy } from '../engine/helpers';
import type { GameState, ModuleInstance, OfflineReason } from '../engine/types';

/** Max battery discharge per minute */
export const MAX_DISCHARGE = 120;
/**
 * Battery reserve: once the battery runs flat, it only supplies power again after recharging to
 * this fraction of capacity. Prevents the last consumer from flickering on and off.
 */
export const RESERVE_RECOVER = 0.25;

export function baseStatus(s: GameState, m: ModuleInstance): OfflineReason | null {
  if (m.buildRemaining > 0) return 'constructing';
  if (!m.enabled) return 'disabled';
  if (m.quarantined) return 'quarantined';
  if (m.condition < 10) return 'broken';
  if (m.overheated) return 'overheated';
  if (m.temperature < MODULES[m.type].minTemp) return 'too_cold';
  const bloom = s.anomalies.find((a) => a.moduleId === m.id && a.kind === 'bloom');
  if (bloom && bloom.intensity >= 90 && !bloom.exploited) return 'overgrown';
  return null;
}

export function reactorOutput(s: GameState, m: ModuleInstance): number {
  const tuning = hasResearch(s, 'eng_reactor_tuning') ? 1 + RESEARCH_EFFECTS.reactorOutput : 1;
  return MODULES.reactor.power * levelMultiplier(m.level) * conditionEfficiency(m.condition) * tuning * captainBonus(s);
}

/** Power demand of a consumer this tick, including Static Choir drain. */
export function powerDemand(s: GameState, m: ModuleInstance): number {
  const def = MODULES[m.type];
  let demand = def.power < 0 ? -def.power * (1 + 0.2 * (m.level - 1)) : 0;
  for (const a of s.anomalies) {
    if (a.moduleId === m.id && a.kind === 'choir' && !a.exploited) demand += a.intensity * 0.2;
  }
  return demand;
}

/** Extra power generated by tapped Static Choir anomalies in this module. */
function choirTapOutput(s: GameState, m: ModuleInstance): number {
  let out = 0;
  for (const a of s.anomalies) if (a.moduleId === m.id && a.kind === 'choir' && a.exploited) out += a.intensity * 0.3;
  return out;
}

export function updatePower(s: GameState, topo: Topology, dtMin: number) {
  const mods = Object.values(s.modules).sort((a, b) => (a.id < b.id ? -1 : 1));
  const reasons = new Map<string, OfflineReason | null>();
  for (const m of mods) reasons.set(m.id, baseStatus(s, m));

  // Network reachability: components over modules that conduct (built and not broken).
  const conducts = (m: ModuleInstance) => m.buildRemaining <= 0 && m.condition >= 10;
  const comps = components(s, topo, conducts);
  const energised = new Set<string>();
  for (const comp of comps) {
    if (comp.some((id) => s.modules[id].type === 'reactor' && reasons.get(id) === null)) comp.forEach((id) => energised.add(id));
  }

  let supply = 0;
  for (const m of mods) {
    m.powerFlow = 0;
    if (m.type === 'reactor' && reasons.get(m.id) === null) {
      const out = reactorOutput(s, m);
      supply += out;
      m.powerFlow = -out;
    }
  }
  for (const m of mods) {
    const tap = reasons.get(m.id) === null && energised.has(m.id) ? choirTapOutput(s, m) : 0;
    if (tap > 0) {
      supply += tap;
      m.powerFlow -= tap;
    }
  }

  if (s.resources.power <= 0.01) s.flags.battery_reserve = true;
  else if (s.resources.power >= s.capacity.power * RESERVE_RECOVER) s.flags.battery_reserve = false;
  const discharge = dtMin > 0 && !s.flags.battery_reserve ? Math.min(MAX_DISCHARGE, s.resources.power / dtMin) : 0;
  const anyReactor = energised.size > 0;
  let remaining = supply + discharge;
  let allocated = 0;
  let shortage = false;
  let totalDemand = 0;

  const consumers = mods
    .filter((m) => m.type !== 'reactor')
    .sort((a, b) => MODULES[a.type].priority - MODULES[b.type].priority || (a.id < b.id ? -1 : 1));

  for (const m of consumers) {
    const reason = reasons.get(m.id) ?? null;
    if (reason !== null) {
      setStatus(m, false, reason);
      continue;
    }
    if (!energised.has(m.id)) {
      setStatus(m, false, anyReactor ? 'disconnected' : 'no_power');
      continue;
    }
    const demand = powerDemand(s, m);
    totalDemand += demand;
    if (demand <= remaining + 1e-9) {
      remaining -= demand;
      allocated += demand;
      m.powerFlow += demand;
      setStatus(m, true, null);
    } else {
      shortage = true;
      setStatus(m, false, 'no_power');
    }
  }
  for (const m of mods) {
    if (m.type !== 'reactor') continue;
    const reason = reasons.get(m.id) ?? null;
    setStatus(m, reason === null, reason);
  }

  const net = supply - allocated;
  s.resources.power = tidy(clamp(s.resources.power + net * dtMin, 0, s.capacity.power));
  s.power = { supply: tidy(supply), demand: tidy(totalDemand), shortage };
  s.flows.power = { production: tidy(supply), consumption: tidy(allocated) };
  if (supply > s.stats.peakPower) s.stats.peakPower = tidy(supply);
}

function setStatus(m: ModuleInstance, powered: boolean, reason: OfflineReason | null) {
  m.powered = powered;
  m.online = powered && reason === null;
  m.offlineReason = reason;
  m.efficiency = m.online ? conditionEfficiency(m.condition) : 0;
}

/** Reactor load 0–1, used for reactor heat. */
export function reactorLoad(s: GameState): number {
  if (s.power.supply <= 0) return 0;
  return clamp(s.flows.power.consumption / s.power.supply, 0, 1);
}
